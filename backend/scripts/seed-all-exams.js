async function seed() {
  try {
    console.log("Connecting to MongoDB:", MONGODB_URI);
    await mongoose.connect(MONGODB_URI, { dbName: "ils-exam-prep" });
    console.log("Connected successfully!");

    const db = mongoose.connection.db;
    const questionsCollection = db.collection("questions");

    for (const q of questionsData) {
      await questionsCollection.updateOne(
        { questionId: q.questionId },
        { $set: q },
        { upsert: true }
      );
      console.log(`Seeded [${q.exam}] ${q.questionId}: ${q.questionText.slice(0, 45)}...`);
    }

    const summary = await questionsCollection.aggregate([
      { $group: { _id: "$exam", count: { $sum: 1 } } }
    ]).toArray();

    console.log("\n=================================");
    console.log("FINAL QUESTION COUNTS PER EXAM:");
    console.log("=================================");
    console.log(JSON.stringify(summary, null, 2));

    await mongoose.disconnect();
    console.log("Database connection closed.");
  } catch (err) {
    console.error("Seeding error:", err);
    process.exit(1);
  }
}

seed();
