async function seedColleges() {
  try {
    console.log("Connecting to MongoDB...");

    await mongoose.connect(MONGODB_URI, {
      dbName: "ils-exam-prep",
      serverSelectionTimeoutMS: 10000,
      connectTimeoutMS: 10000,
    });

    console.log("MongoDB connected.");

    // Clear old test dummy records
    await College.deleteMany({
      name: { $regex: /Development/i },
    });
    console.log("Cleaned up old dummy development records.");

    for (const college of colleges) {
      const result = await College.findOneAndUpdate(
        {
          name: college.name,
          exam: college.exam,
        },
        {
          $set: college,
        },
        {
          upsert: true,
          new: true,
          setDefaultsOnInsert: true,
        }
      );

      console.log(`Seeded/updated: ${result.name} (${result.exam.toUpperCase()})`);
    }

    console.log(`\nSuccessfully seeded ${colleges.length} real institutions.`);
  } catch (error) {
    console.error("College seed failed:");
    console.error(error);
    process.exitCode = 1;
  } finally {
    await mongoose.disconnect();
    console.log("MongoDB connection closed.");
  }
}

seedColleges();